using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace HRMBT.Web.Models;

/// <summary>HR's record of an attendance fix (forgotten check-out and the like). Append-only; raw punches are never overwritten.</summary>
public class AttendanceCorrection
{
    [Key]
    public int Id { get; set; }
    public int AttendanceId { get; set; }

    [Required, StringLength(20)]
    public string CorrectionType { get; set; } = string.Empty;

    public DateTime? CorrectedCheckInAt { get; set; }
    public DateTime? CorrectedCheckOutAt { get; set; }

    [StringLength(20)]
    public string? OldDayStatus { get; set; }

    [StringLength(20)]
    public string? NewDayStatus { get; set; }

    public DateTime? ReportedByEmployeeAt { get; set; }

    [Required, StringLength(500)]
    public string Reason { get; set; } = string.Empty;

    public int RecordedByUserId { get; set; }
    public DateTime CreatedAt { get; set; }

    /// <summary>Idempotency key generated by the form (S21).</summary>
    public Guid? RequestId { get; set; }
}
