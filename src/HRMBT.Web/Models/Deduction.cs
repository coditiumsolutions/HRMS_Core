using System;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Microsoft.AspNetCore.Mvc.ModelBinding.Validation;

namespace HRMBT.Web.Models
{
    /// <summary>Maps to dbo.Deductions (see db.md). Fixed PKR amounts use <see cref="PercentageValue"/> when <see cref="CalculationMethod"/> is Fixed (no separate Amount column).</summary>
    public class Deduction
    {
        [Key]
        public int Id { get; set; }

        [Display(Name = "Employee")]
        public int EmployeeId { get; set; }

        [Required]
        [StringLength(50)]
        [Display(Name = "Deduction type")]
        public string DeductionType { get; set; } = string.Empty;

        [Required]
        [StringLength(100)]
        [Display(Name = "Deduction name")]
        public string DeductionName { get; set; } = string.Empty;

        [Required]
        [StringLength(50)]
        [Display(Name = "Frequency")]
        public string Frequency { get; set; } = "Monthly";

        [Required]
        [StringLength(50)]
        [Display(Name = "Calculation method")]
        public string CalculationMethod { get; set; } = string.Empty;

        /// <summary>Percentage of gross (when method is Percentage) or fixed PKR amount (when method is Fixed).</summary>
/// <summary>Stored percentage (0-100); only used when CalculationMethod is Percentage.</summary>
        public decimal? Percentage { get; set; }

        private decimal? _value;
        private bool _valueSet;

        /// <summary>
        /// The deduction's value as the screens see it: a percentage for Percentage deductions, PKR for Fixed ones.
        /// Stored in the Percentage column (percent) or the Amount column (fixed) according to CalculationMethod.
        /// </summary>
        [NotMapped]
        [Display(Name = "Percentage / fixed amount")]
        public decimal? PercentageValue
        {
            get => _valueSet ? _value : (IsPercentageMethod ? Percentage : Amount);
            set { _value = value; _valueSet = true; }
        }

        private bool IsPercentageMethod =>
            string.Equals(CalculationMethod, "Percentage", StringComparison.OrdinalIgnoreCase);

        /// <summary>Writes the facade value into the right column and clears the other. Called by the DbContext before saving.</summary>
        public void ApplyFacade()
        {
            if (_valueSet)
            {
                if (IsPercentageMethod) { Percentage = _value; Amount = null; }
                else { Amount = _value; Percentage = null; }
                _valueSet = false;
            }
            else if (IsPercentageMethod) Amount = null;
            else Percentage = null;
        }

        /// <summary>Fixed amount when CalculationMethod is Fixed (PercentageValue is percentage-only).</summary>
        [Display(Name = "Fixed amount")]
        public decimal? Amount { get; set; }

        [StringLength(1000)]
        public string? Notes { get; set; }

        [Display(Name = "Mandatory")]
        public bool IsMandatory { get; set; }

        [Display(Name = "Effective date")]
        [DataType(DataType.Date)]
        public DateTime EffectiveDate { get; set; }

        [Display(Name = "End date")]
        [DataType(DataType.Date)]
        public DateTime? EndDate { get; set; }

        [Display(Name = "Active")]
        public bool IsActive { get; set; }

        public DateTime CreatedDate { get; set; }

        [StringLength(100)]
        public string CreatedBy { get; set; } = string.Empty;

        public DateTime? ModifiedDate { get; set; }

        [StringLength(100)]
        public string? ModifiedBy { get; set; }

        /// <summary>Idempotency key generated by the create form: a replayed POST is recognised as "already saved" (S21).</summary>
        public Guid? RequestId { get; set; }

        [ForeignKey("EmployeeId")]
        [ValidateNever]
        public Employee? Employee { get; set; }
    }
}
